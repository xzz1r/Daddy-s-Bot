// Se le habla a una persona: tú. Cuando el bot le habla al grupo, vosotros
// (nunca ustedes), que es el plural que eligió el dueño.
// El tiempo restante NO va aquí: el caller lo pone en el footer `_Vuelve en *…*._`.
// Sin placeholders. pickFresh vive en helpers; fraseCooldown lo envuelve.

const { pickFresh } = require('../utils/helpers');

// mix: probabilidad de caer al pool genérico. 0 = siempre el específico.
function fraseCooldown(especifico, clave, mix = 0.18) {
  const hay = Array.isArray(especifico) && especifico.length;
  const usarEsp = hay && Math.random() >= mix;
  const pool = usarEsp ? especifico : GENERICO;
  const k = usarEsp ? clave : `${clave}|gen`;
  return pickFresh(pool, k);
}

